"""Hatch build hook that generates the aspected_client package from openapi.json."""

from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import Counter
from copy import deepcopy
from pathlib import Path
from typing import Any

from hatchling.builders.hooks.plugin.interface import BuildHookInterface


class GenerateClientBuildHook(BuildHookInterface):
    """Custom build hook that generates client code from the OpenAPI spec before building."""

    PLUGIN_NAME = "generate-client"

    def initialize(self, version: str, build_data: dict[str, Any]) -> None:
        """Run code generation before build."""
        root = Path(self.root)
        self._root = root
        self._templates_dir = root / "templates"
        self._openapi_path = root / "openapi.json"
        self._output_dir = root / "src" / "aspected_client"
        self._model_output = self._output_dir / "model.py"
        self._client_output = self._output_dir / "client.py"
        self._init_output = self._output_dir / "__init__.py"
        self._file_header = "# This file is automatically generated, do not edit this file"

        spec = json.loads(self._openapi_path.read_text())
        preprocessed = _preprocess_spec(spec)

        self._ensure_package_dir()
        self._generate_models(preprocessed)
        self._generate_client(spec)
        self._generate_init()
        self._run_formatters()
        self._apply_patches()

    def _ensure_package_dir(self) -> None:
        """Create the target package directory and py.typed marker if needed."""
        self._output_dir.mkdir(parents=True, exist_ok=True)
        py_typed = self._output_dir / "py.typed"
        if not py_typed.exists():
            py_typed.write_text("")

    def _generate_models(self, spec: dict) -> None:
        """Generate model.py from the preprocessed OpenAPI spec using datamodel-codegen."""
        spec_json = json.dumps(spec)

        cmd = [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--output",
            str(self._model_output),
            "--input-file-type",
            "openapi",
            "--preset",
            "practical-py312-20260619",
            "--openapi-scopes",
            "schemas",
            "paths",
            "--use-title-as-name",
            "--use-type-alias",
            "--custom-file-header",
            self._file_header,
            "--formatters",
            "ruff-check",
            "ruff-format",
        ]
        result = subprocess.run(
            cmd,
            cwd=self._root,
            input=spec_json,
            text=True,
            capture_output=True,
        )
        if result.returncode != 0:
            sys.stderr.write(result.stdout)
            sys.stderr.write(result.stderr)
            result.check_returncode()

    def _generate_client(self, spec: dict) -> None:
        """Generate client.py from the OpenAPI spec using the Jinja2 template."""
        from jinja2 import Environment, FileSystemLoader

        operations = _build_operations(spec)

        imports: set[str] = set()
        for op in operations:
            if op["request_class"]:
                imports.add(op["request_class"])
            imports.add(op["response_class"])

        sorted_imports = sorted(imports)

        env = Environment(
            loader=FileSystemLoader(str(self._templates_dir)),
            keep_trailing_newline=True,
        )
        template = env.get_template("client.py.j2")

        rendered = template.render(
            operations=operations,
            imports=sorted_imports,
            header=self._file_header,
        )

        self._client_output.write_text(rendered)

    def _generate_init(self) -> None:
        """Generate __init__.py that re-exports the client and all model classes."""
        from jinja2 import Environment, FileSystemLoader

        model_source = self._model_output.read_text()
        model_imports = sorted(
            re.findall(r"^(?:class|type) (\w+)[\s(=]", model_source, re.MULTILINE)
        )

        env = Environment(
            loader=FileSystemLoader(str(self._templates_dir)),
            keep_trailing_newline=True,
        )
        template = env.get_template("__init__.py.j2")

        rendered = template.render(model_imports=model_imports, header=self._file_header)

        self._init_output.write_text(rendered)

    def _run_formatters(self) -> None:
        """Run ruff format and check --fix on the generated files."""
        generated_files = [
            str(self._client_output),
            str(self._model_output),
            str(self._init_output),
        ]

        result = subprocess.run(
            ["ruff", "format", *generated_files],
            cwd=self._root,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            sys.stderr.write(result.stdout)
            sys.stderr.write(result.stderr)
            result.check_returncode()

        result = subprocess.run(
            ["ruff", "check", "--fix", "--ignore", "E501", *generated_files],
            cwd=self._root,
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            sys.stderr.write(result.stdout)
            sys.stderr.write(result.stderr)
            result.check_returncode()

    def _apply_patches(self) -> None:
        """Apply all patch files from the patches directory.

        Uses the pure-Python ``patch-ng`` library instead of ``git apply`` or
        the system ``patch`` binary. This avoids two portability problems:

        - Build backends (e.g. uv) may build in an isolated temp directory
          that contains only a sentinel ``.git`` file (not a real
          repository), which makes ``git apply`` fail with "not a git
          repository".
        - The ``patch`` command-line utility isn't reliably available on
          Windows.

        ``patch-ng`` has no such dependencies and works identically on all
        platforms.
        """
        import patch_ng

        patches_dir = self._root / "patches"
        if not patches_dir.is_dir():
            return

        for patch_file in sorted(patches_dir.glob("*.patch")):
            patch_set = patch_ng.fromfile(str(patch_file))
            if not patch_set:
                raise RuntimeError(f"Failed to parse patch {patch_file.name}")
            if not patch_set.apply(root=str(self._root)):
                raise RuntimeError(f"Failed to apply patch {patch_file.name}")


