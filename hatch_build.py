# Helpers (moved from generate_client.py)
# ---------------------------------------------------------------------------


def _snake_case(name: str) -> str:
    """Convert camelCase operationId to snake_case method name."""
    s1 = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s1).lower()


def _pascal_case(name: str) -> str:
    """Convert operationId to PascalCase (for Request/Response class names)."""
    return name[0].upper() + name[1:]


def _openapi_type_to_python(schema: dict) -> str:
    """Map an OpenAPI schema type to a Python type hint string."""
    t = schema.get("type", "string")
    mapping = {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "array": "list",
        "object": "dict",
    }
    return mapping.get(t, "str")


def _build_operations(spec: dict) -> list[dict]:
    """Extract operation metadata from the OpenAPI spec."""
    ops: list[dict] = []
    params_registry = spec.get("components", {}).get("parameters", {})

    for path, methods in spec.get("paths", {}).items():
        for http_method, details in methods.items():
            if http_method not in ("get", "post", "put", "delete", "patch"):
                continue

            operation_id = details["operationId"]
            method_name = _snake_case(operation_id)
            summary = details.get("summary", "")
            description = details.get("description", "")

            path_params: list[dict] = []
            query_params: list[dict] = []

            for param in details.get("parameters", []):
                if "$ref" in param:
                    ref_name = param["$ref"].split("/")[-1]
                    param = params_registry[ref_name]

                schema = param.get("schema", {})
                p = {
                    "name": param["name"],
                    "python_name": _snake_case(param["name"]),
                    "required": param.get("required", False),
                    "type": _openapi_type_to_python(schema),
                    "description": param.get("description", ""),
                }
                if param["in"] == "path":
                    path_params.append(p)
                elif param["in"] == "query":
                    query_params.append(p)

            has_body = "requestBody" in details
            request_class = f"{_pascal_case(operation_id)}Payload" if has_body else None
            response_class = f"{_pascal_case(operation_id)}Result"

            url_template = path
            for pp in path_params:
                url_template = url_template.replace(
                    "{" + pp["name"] + "}", "{" + pp["python_name"] + "}"
                )

            ops.append(
                {
                    "method_name": method_name,
                    "http_method": http_method,
                    "url_template": url_template,
                    "path_params": path_params,
                    "query_params": query_params,
                    "has_body": has_body,
                    "request_class": request_class,
                    "response_class": response_class,
                    "summary": summary,
                    "description": description,
                }
            )

    return ops


