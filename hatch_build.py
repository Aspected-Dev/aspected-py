def _to_pascal_case(name: str) -> str:
    """Convert a field name (camelCase or snake_case) to PascalCase."""
    if "_" in name:
        return "".join(part.capitalize() for part in name.split("_"))
    return name[0].upper() + name[1:]


def _is_schema_node(node: dict) -> bool:
    """Check if a dict is an OpenAPI schema that would generate a named type."""
    if not isinstance(node, dict):
        return False
    if node.get("type") == "object" and "properties" in node:
        return True
    return "allOf" in node


def _ensure_titles(node: dict | list, field_name: str | None = None) -> None:
    """Walk schemas and ensure every object/array schema has a title."""
    if isinstance(node, list):
        for item in node:
            if isinstance(item, (dict, list)):
                _ensure_titles(item, field_name)
        return

    if not isinstance(node, dict):
        return

    if "$ref" in node:
        return

    if _is_schema_node(node) and "title" not in node and field_name:
        node["title"] = _to_pascal_case(field_name)

    if "properties" in node and isinstance(node["properties"], dict):
        for prop_name, prop_schema in node["properties"].items():
            if isinstance(prop_schema, dict):
                _ensure_titles(prop_schema, prop_name)

    if "items" in node and isinstance(node["items"], dict):
        _ensure_titles(node["items"], field_name)

    for keyword in ("allOf", "oneOf", "anyOf"):
        if keyword in node and isinstance(node[keyword], list):
            for item in node[keyword]:
                if isinstance(item, dict):
                    _ensure_titles(item, field_name)


def _ensure_titles_in_spec(spec: dict) -> None:
    """Add missing titles to all schemas in paths and components/schemas."""
    schemas = spec.get("components", {}).get("schemas", {})
    for schema_name, schema_obj in schemas.items():
        if isinstance(schema_obj, dict):
            if _is_schema_node(schema_obj) and "title" not in schema_obj:
                schema_obj["title"] = schema_name
            _ensure_titles(schema_obj, schema_name)

    for _path, methods in spec.get("paths", {}).items():
        if not isinstance(methods, dict):
            continue
        for _method, operation in methods.items():
            if not isinstance(operation, dict):
                continue
            req_body = (
                operation.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            if isinstance(req_body, dict):
                _ensure_titles(req_body, None)

            for _status, response in operation.get("responses", {}).items():
                if not isinstance(response, dict):
                    continue
                resp_schema = response.get("content", {}).get("application/json", {}).get("schema")
                if isinstance(resp_schema, dict):
                    _ensure_titles(resp_schema, None)


def _collect_titles(node: dict | list, parent_title: str | None = None) -> list[dict]:
    """Walk the spec tree and collect all objects that have a 'title' key."""
    results: list[dict] = []
    if isinstance(node, dict):
        title_val = node.get("title")
        current_title = title_val if isinstance(title_val, str) else None
        effective_parent = parent_title
        if current_title is not None:
            results.append(
                {
                    "obj": node,
                    "title": current_title,
                    "parent_title": parent_title,
                }
            )
            effective_parent = current_title
        for value in node.values():
            if isinstance(value, (dict, list)):
                results.extend(_collect_titles(value, effective_parent))
    elif isinstance(node, list):
        for item in node:
            if isinstance(item, (dict, list)):
                results.extend(_collect_titles(item, parent_title))
    return results


def _preprocess_spec(spec: dict) -> dict:
    """Rename titles: Request→Payload, Response→Result, then resolve collisions."""
    spec = deepcopy(spec)

    _ensure_titles_in_spec(spec)

    def _collect_from_spec(s: dict) -> list[dict]:
        entries: list[dict] = []
        if "paths" in s:
            entries.extend(_collect_titles(s["paths"]))
        schemas = s.get("components", {}).get("schemas")
        if schemas:
            entries.extend(_collect_titles(schemas))
        return entries

    # Step 1: Rename suffixes
    entries = _collect_from_spec(spec)
    for entry in entries:
        title = entry["obj"]["title"]
        if title.endswith("Request"):
            entry["obj"]["title"] = title[: -len("Request")] + "Payload"
        elif title.endswith("Response"):
            entry["obj"]["title"] = title[: -len("Response")] + "Result"

    # Step 2: Set titles on request/response schemas using operationId
    for _path, methods in spec.get("paths", {}).items():
        if not isinstance(methods, dict):
            continue
        for _method, operation in methods.items():
            if not isinstance(operation, dict):
                continue
            op_id = operation.get("operationId")
            if not op_id:
                continue
            pascal = _pascal_case(op_id)

            req_schema = (
                operation.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            if isinstance(req_schema, dict):
                req_schema["title"] = f"{pascal}Payload"

            resp_schema = (
                operation.get("responses", {})
                .get("200", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            if isinstance(resp_schema, dict):
                resp_schema["title"] = f"{pascal}Result"

    # Step 3: Resolve collisions iteratively
    while True:
        entries = _collect_from_spec(spec)
        title_counts = Counter(e["title"] for e in entries)
        colliding_titles = {t for t, count in title_counts.items() if count > 1}

        if not colliding_titles:
            break

        for entry in entries:
            if entry["title"] in colliding_titles:
                parent = entry["parent_title"]
                if parent:
                    entry["obj"]["title"] = parent + entry["title"]

    return spec
